export function getCategoryBySlug(slug: string): Category | undefined {
  return categories.find((c) => c.slug === slug);
}

export function getAllCategorySlugs(): string[] {
  return categories.map((c) => c.slug);
}

export function getActiveCategories(): Category[] {
  return categories.filter((c) => c.isActive).sort((a, b) => a.sortOrder - b.sortOrder);
}

export function getSubcategoryBySlug(categorySlug: string, subcategorySlug: string) {
  const category = getCategoryBySlug(categorySlug);
  if (!category?.subcategories) return undefined;
  return category.subcategories.find((s) => s.slug === subcategorySlug);
}

export function getAllSubcategorySlugs(): { category: string; subcategory: string }[] {
  const slugs: { category: string; subcategory: string }[] = [];
  for (const cat of categories) {
    if (cat.subcategories) {
      for (const sub of cat.subcategories) {
        slugs.push({ category: cat.slug, subcategory: sub.slug });
      }
    }
  }
  return slugs;
}
